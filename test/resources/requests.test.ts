describe("Idempotency-Key on the creates the API makes idempotent", () => {
  const creates: [string, Call, string][] = [
    ["users.create", (c) => c.users.create({ tenant_id: "t1", email: "a@b.in" }), "/v1/users"],
    ["groups.create", (c) => c.groups.create({ tenant_id: "t1", name: "Finance" }), "/v1/groups"],
    ["invitations.create", (c) => c.invitations.create({ tenant_id: "t1", email: "a@b.in" }), "/v1/invites"],
    ["servicePrincipals.create", (c) => c.servicePrincipals.create({ tenant_id: "t1", name: "etl" }), "/v1/service-principals"],
    ["apiKeys.create", (c) => c.apiKeys.create({ tenant_id: "t1", name: "ci" }), "/v1/api-keys"],
    ["agents.create", (c) => c.agents.create("t1", { name: "bot", sponsor_user_id: "u1" }), "/v1/tenants/t1/agents"],
    ["webhooks.create", (c) => c.webhooks.create({ url: "https://h.example", events: ["user.created"] }), "/v1/webhooks"],
    [
      "billing.checkout",
      (c) =>
        c.billing.checkout("t1", { plan_code: "pro", currency: "INR", success_url: "https://a.example", cancel_url: "https://a.example" }),
      "/v1/tenants/t1/billing/checkout",
    ],
    [
      "billing.payInvoice",
      (c) => c.billing.payInvoice("t1", "inv1", { success_url: "https://a.example", cancel_url: "https://a.example" }),
      "/v1/tenants/t1/billing/invoices/inv1/pay",
    ],
  ];

  it.each(creates)("%s sends one, generated when not given", async (_name, call, path) => {
    const { client, requests } = mockClient([{ status: 201, body: {} }]);
    await call(client);
    expect(requests[0]?.path).toBe(path);
    expect(requests[0]?.headers.get("idempotency-key")).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
  });

  it("sends none on other writes", async () => {
    const { client, requests } = mockClient([{ status: 201, body: {} }]);
    await client.roles.create("t1", { name: "Auditor" });
    await client.domains.create("t1", { domain: "brightleaffoods.in" });
    expect(requests.every((r) => !r.headers.has("idempotency-key"))).toBe(true);
  });
});
